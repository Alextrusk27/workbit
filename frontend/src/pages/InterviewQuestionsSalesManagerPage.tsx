function trainingPath(skill: string, level: 'EASY' | 'MEDIUM'): string {
  return `/app/training/new?${new URLSearchParams({
    profession: PROFESSION,
    skill,
    level,
  }).toString()}`
}

function Section({
  id,
  title,
  children,
}: {
  id: string
  title: string
  children: ReactNode
}) {
  return (
    <section id={id} className="pb-10 sm:pb-14">
      <Container>
        <Reveal>
          <div className="mx-auto max-w-[72ch]">
            <h2 className="text-ink text-[clamp(26px,3.2vw,36px)]">{title}</h2>
            <div className="mt-5 flex flex-col gap-4">{children}</div>
          </div>
        </Reveal>
      </Container>
    </section>
  )
}

function Prose({ children }: { children: ReactNode }) {
  return <p className="text-muted text-[16px] leading-relaxed">{children}</p>
}

function LeadList({ items }: { items: { lead: string; rest: string }[] }) {
  return (
    <ul className="flex flex-col gap-3.5">
      {items.map((item) => (
        <li key={item.lead} className="flex gap-3">
          <span
            aria-hidden
            className="bg-indigo mt-2.5 size-1.5 shrink-0 rounded-full"
          />
          <span className="text-muted text-[16px] leading-relaxed">
            <strong className="text-ink font-semibold">{item.lead}</strong>
            {item.rest}
          </span>
        </li>
      ))}
    </ul>
  )
}

function TrainLink({
  to,
  target,
  children,
  variant = 'primary',
}: {
  to: string
  target: string
  children: ReactNode
  variant?: 'primary' | 'secondary'
}) {
  return (
    <Link
      to={to}
      state={{ from: { pathname: target } }}
      className={buttonClasses({ variant, className: 'px-7' })}
    >
      {children}
    </Link>
  )
}

