package ru.workbit.speech.dto;

/**
 * Гипотеза распознавания во внутреннем виде — то, что клиент SpeechKit отдаёт слушателю.
 *
 * @param kind вид гипотезы
 * @param text непустой распознанный текст
 */
public record SttResult(Kind kind, String text) {

    /**
     * Вид гипотезы. Схлопывать их нельзя: {@link #PARTIAL} перезаписывается по ходу речи,
     * {@link #FINAL} закрывает фразу, а {@link #REFINEMENT} приходит следом и уточняет её.
     */
    public enum Kind {
        /** Промежуточная гипотеза: текст ещё меняется, годится только для подсказки на экране. */
        PARTIAL,
        /** Итоговый текст фразы без нормализации — без пунктуации и с числами словами. */
        FINAL,
        /** Нормализованный текст той же фразы: пунктуация, числа цифрами. Приходит после FINAL. */
        REFINEMENT
    }
}
